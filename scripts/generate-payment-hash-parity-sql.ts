/*
 * Generates scripts/sql/payment-hash-parity-check.sql from
 * tests/fixtures/payment-canonical-vectors.json (Payments Phase 2, step 3, B3).
 *
 * The generated script is for B4 ONLY: run it on filumire_test AFTER 0019 is
 * applied, in a READ ONLY transaction that is rolled back. It calls the 0019
 * functions payment_purchase_canonical_text / payment_purchase_hash with every
 * vector and fails (RAISE EXCEPTION) on any difference from the TypeScript
 * results, any refused valid vector or any accepted invalid vector. It also
 * hashes each expected text with PostgreSQL's own sha256 (encoding check that
 * does not depend on the 0019 functions).
 *
 *   npx tsx scripts/generate-payment-hash-parity-sql.ts          (writes the file)
 * tests/payment-canonical-vectors.test.ts fails if the file is stale.
 * No database, no network.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const FIXTURE_PATH = "tests/fixtures/payment-canonical-vectors.json";
export const PARITY_SQL_PATH = "scripts/sql/payment-hash-parity-check.sql";

interface VectorInput {
  id: string;
  payerPrincipalId: string;
  productCode: string;
  productVersion: string;
  productLabel: string;
  termsJson: string;
  amountMinor: number;
  currency: string;
  mode: string;
  learnerIds: string[];
}

interface Fixture {
  valid: Array<{ name: string; input: VectorInput; expected: { canonicalText: string; sha256: string } }>;
  invalid: Array<{ name: string; input: VectorInput; why: string }>;
  formatting: Array<{ name: string; input: VectorInput; sqlExpected: "same_hash" | "refused"; tsExpected: { sha256: string } }>;
}

/*
 * UTF-8 bytes of a JS string, encoding unpaired surrogates as their 3-byte
 * (invalid) form instead of U+FFFD, so PostgreSQL sees exactly what the
 * application would send and refuses it.
 */
function wtf8Hex(value: string): string {
  const bytes: number[] = [];
  for (let i = 0; i < value.length; i += 1) {
    let cp = value.charCodeAt(i);
    if (cp >= 0xd800 && cp <= 0xdbff && i + 1 < value.length) {
      const low = value.charCodeAt(i + 1);
      if (low >= 0xdc00 && low <= 0xdfff) {
        cp = 0x10000 + ((cp - 0xd800) << 10) + (low - 0xdc00);
        i += 1;
      }
    }
    if (cp < 0x80) bytes.push(cp);
    else if (cp < 0x800) bytes.push(0xc0 | (cp >> 6), 0x80 | (cp & 0x3f));
    else if (cp < 0x10000) bytes.push(0xe0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));
    else bytes.push(0xf0 | (cp >> 18), 0x80 | ((cp >> 12) & 0x3f), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));
  }
  return Buffer.from(bytes).toString("hex");
}

/* A SQL text literal: plain for printable ASCII, otherwise decoded from UTF-8 hex (no escaping ambiguity). */
function text(value: string): string {
  if (/^[\x20-\x7e]*$/.test(value)) return `'${value.replace(/'/g, "''")}'`;
  return `convert_from(decode('${wtf8Hex(value)}', 'hex'), 'UTF8')`;
}

function args(input: VectorInput): string {
  const learners = input.learnerIds.length === 0 ? "ARRAY[]::text[]" : `ARRAY[${input.learnerIds.map(text).join(", ")}]::text[]`;
  return [
    text(input.id),
    text(input.payerPrincipalId),
    text(input.productCode),
    text(input.productVersion),
    text(input.productLabel),
    `(${text(input.termsJson)})::jsonb`,
    /* As node-pg sends an integer parameter: its decimal text. */
    `'${String(input.amountMinor)}'::integer`,
    text(input.currency),
    text(input.mode),
    learners,
  ].join(",\n      ");
}

export function buildParitySql(fixture: Fixture): string {
  const out: string[] = [];
  out.push(
    "-- GENERATED by scripts/generate-payment-hash-parity-sql.ts from tests/fixtures/payment-canonical-vectors.json. Do not edit.",
    "-- Payments Phase 2, step 3: TypeScript / PostgreSQL canonical purchase hash parity.",
    "-- B4 ONLY: run on filumire_test AFTER migration 0019, e.g.",
    "--   psql \"<filumire_test url>\" -v ON_ERROR_STOP=1 -f scripts/sql/payment-hash-parity-check.sql",
    "-- Read-only and rolled back. Exit status non-zero = parity NOT proven.",
    "BEGIN;",
    "SET TRANSACTION READ ONLY;",
    "SET LOCAL standard_conforming_strings = on;",
    "DO $parity$",
    "DECLARE",
    "  failures integer := 0;",
    "  valid_ok integer := 0;",
    "  invalid_refused integer := 0;",
    "  formatting_ok integer := 0;",
    "  got text;",
    "BEGIN",
    "  IF current_database() <> 'filumire_test' THEN",
    "    RAISE EXCEPTION 'hash parity check runs on filumire_test only';",
    "  END IF;",
  );
  for (const v of fixture.valid) {
    const name = v.name.replace(/'/g, "''");
    out.push(
      `  -- valid: ${v.name}`,
      "  BEGIN",
      `    got := payment_purchase_canonical_text(\n      ${args(v.input)});`,
      `    IF got IS DISTINCT FROM ${text(v.expected.canonicalText)} THEN`,
      `      failures := failures + 1; RAISE WARNING 'canonical text differs: ${name}';`,
      "    END IF;",
      `    IF encode(sha256(convert_to(got, 'UTF8')), 'hex') IS DISTINCT FROM '${v.expected.sha256}' THEN`,
      `      failures := failures + 1; RAISE WARNING 'sha256 differs: ${name}';`,
      "    END IF;",
      `    IF payment_purchase_hash(\n      ${args(v.input)}) IS DISTINCT FROM '${v.expected.sha256}' THEN`,
      `      failures := failures + 1; RAISE WARNING 'payment_purchase_hash differs: ${name}';`,
      "    END IF;",
      `    IF encode(sha256(convert_to(${text(v.expected.canonicalText)}, 'UTF8')), 'hex') <> '${v.expected.sha256}' THEN`,
      `      failures := failures + 1; RAISE WARNING 'UTF-8 encoding of the expected text differs: ${name}';`,
      "    END IF;",
      "    valid_ok := valid_ok + 1;",
      "  EXCEPTION WHEN OTHERS THEN",
      `    failures := failures + 1; RAISE WARNING 'valid vector refused: ${name} (%: %)', SQLSTATE, SQLERRM;`,
      "  END;",
    );
  }
  for (const v of fixture.invalid) {
    const name = v.name.replace(/'/g, "''");
    out.push(
      `  -- invalid: ${v.name} (${v.why.replace(/\n/g, " ")})`,
      "  BEGIN",
      `    got := payment_purchase_hash(\n      ${args(v.input)});`,
      `    failures := failures + 1; RAISE WARNING 'invalid vector accepted: ${name}';`,
      "  EXCEPTION WHEN OTHERS THEN",
      `    invalid_refused := invalid_refused + 1; RAISE NOTICE 'refused as expected: ${name} (%)', SQLSTATE;`,
      "  END;",
    );
  }
  for (const v of fixture.formatting) {
    const name = v.name.replace(/'/g, "''");
    if (v.sqlExpected === "same_hash") {
      out.push(
        `  -- formatting (expected same hash as TypeScript): ${v.name}`,
        "  BEGIN",
        `    IF payment_purchase_hash(\n      ${args(v.input)}) IS DISTINCT FROM '${v.tsExpected.sha256}' THEN`,
        `      failures := failures + 1; RAISE WARNING 'formatting vector hash differs: ${name}';`,
        "    ELSE formatting_ok := formatting_ok + 1;",
        "    END IF;",
        "  EXCEPTION WHEN OTHERS THEN",
        `    failures := failures + 1; RAISE WARNING 'formatting vector refused: ${name} (%: %)', SQLSTATE, SQLERRM;`,
        "  END;",
      );
    } else {
      out.push(
        `  -- formatting (expected refused by SQL): ${v.name}`,
        "  BEGIN",
        `    got := payment_purchase_hash(\n      ${args(v.input)});`,
        `    failures := failures + 1; RAISE WARNING 'formatting vector accepted, expected refusal: ${name}';`,
        "  EXCEPTION WHEN OTHERS THEN",
        "    formatting_ok := formatting_ok + 1;",
        "  END;",
      );
    }
  }
  out.push(
    "  IF failures > 0 THEN",
    "    RAISE EXCEPTION 'payment hash parity FAILED: % problem(s)', failures;",
    "  END IF;",
    `  RAISE NOTICE 'payment hash parity OK: % of ${fixture.valid.length} valid, % of ${fixture.invalid.length} invalid refused, % of ${fixture.formatting.length} formatting', valid_ok, invalid_refused, formatting_ok;`,
    "END",
    "$parity$;",
    "ROLLBACK;",
    "",
  );
  return out.join("\n");
}

export function loadFixture(): Fixture {
  return JSON.parse(readFileSync(FIXTURE_PATH, "utf8")) as Fixture;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(PARITY_SQL_PATH, buildParitySql(loadFixture()), "utf8");
  console.log(`wrote ${PARITY_SQL_PATH}`);
}
