/*
 * FILUMIRE payment contract v2 (Payments Phase 2, step 1).
 *
 * Provider-independent. Billing is separate from learning:
 * - the PAYER is an adult principal (guardian, or an adult learning for
 *   themself); a child learner is never the payer, and no learner id is ever
 *   sent to a payment provider;
 * - payments never read or write learner state, evidence or mastery;
 * - amounts are integer minor units (see ./money).
 *
 * Canonical flow (architecture spec section 24):
 * Provider -> Payment Adapter -> Transaction/Subscription -> Entitlement Engine -> Access.
 */
import type { Money } from "./money";

export * from "./money";
export * from "./verification";
export * from "./intent";
export * from "./errors";
export * from "./lifecycle";
export * from "./obligation";

export type PaymentProviderId = "fake" | "paystack";

export type PaymentMode = "sandbox" | "live";

/* Normalised provider status. Only "successful" can ever lead to access. */
export type ProviderPaymentStatus =
  | "pending"
  | "successful"
  | "failed"
  | "abandoned"
  | "reversed";

export type PaymentChannel = "card" | "mobile_money" | "bank" | "other";

/* Who pays: an adult principal with contact details the provider can use. */
export interface PaymentPayer {
  principalId: string;
  email: string;
  phone?: string;
}

/*
 * What FILUMIRE asks a provider to collect. ourReference is generated by
 * FILUMIRE, unique per attempt, and is the idempotency key for the attempt.
 */
export interface PaymentIntent {
  ourReference: string;
  amount: Money;
  payer: PaymentPayer;
  description: string;
  /* Billing account the payment is for (not a learner). */
  billingAccountId?: string;
}

export interface InitiatedPayment {
  provider: PaymentProviderId;
  ourReference: string;
  providerReference: string;
  next:
    | { type: "redirect"; url: string }
    | { type: "await_customer" };
}

/* What the provider reports, normalised. Never trusted until verified against the intent. */
export interface ObservedPayment {
  provider: PaymentProviderId;
  providerReference: string;
  ourReference: string;
  status: ProviderPaymentStatus;
  amountMinor: number;
  currency: string;
  channel?: PaymentChannel;
  paidAt?: string;
}

export interface PaymentProviderAdapter {
  readonly id: PaymentProviderId;
  readonly mode: PaymentMode;
  initiate(intent: PaymentIntent): Promise<InitiatedPayment>;
  /* Looks a payment up by FILUMIRE's reference. */
  verify(ourReference: string): Promise<ObservedPayment>;
}
